"""CI regression gate: fails the build if the CURRENT run's per-task val
metrics, or calibration ECE, are worse than a committed floor.

Two checks, both against ml/results/metric_thresholds.json:

  1. Per-task metric regression: for every task registered in
     models/production/metadata.json, compare its CURRENT val metric
     (PR-AUC for classification, RMSE for regression) against the
     committed floor value for that task, with a small tolerance
     (0.035 absolute for classification PR-AUC, 0.02 for regression RMSE
     - see "tolerance" in the threshold file). Classification tolerance
     is wider than regression's because RandomForest/XGBoost training
     (n_jobs=-1) is not perfectly bit-reproducible run-to-run even with
     a fixed random_state - SR-MMP in particular has documented val-PR-AUC
     jitter of ~0.02 between runs (see ml/TODO_evaluation_validation.md's
     CV-vs-val-split finding), so 0.02 tolerance produced false-positive
     CI failures on a genuinely non-regressed model.
     Classification fails if current PR-AUC < floor - tolerance.
     Regression fails if current RMSE > floor + tolerance.

  2. Calibration regression: for the 4 representative tasks explored in
     ml/calibration.py (NR-AR, SR-MMP, bbbp_penetration, ct_tox), compare
     the CURRENT Platt-scaled (sigmoid) val ECE against the committed
     floor, with tolerance (default 0.05 absolute). Fails if current ECE
     > floor + tolerance (ECE getting worse = probabilities less
     trustworthy).

This is a real gate, not a decorative one: it reads whatever
models/production/metadata.json and ml/results/calibration_metrics.json
say RIGHT NOW (freshly regenerated earlier in the same CI run, after
"Run model registry" / "Run calibration + applicability domain") and
exits non-zero the moment either has regressed past its committed floor.

ml/results/metric_thresholds.json is a committed file, not regenerated
by this script. To deliberately move the floor after a reviewed,
intentional metric change (e.g. a genuinely better model, or an accepted
trade-off), regenerate it explicitly - do not hand-edit thresholds down
just to make a real regression pass:

    python -c "
    import json
    meta = json.load(open('models/production/metadata.json'))
    calib = json.load(open('ml/results/calibration_metrics.json'))
    thresholds = json.load(open('ml/results/metric_thresholds.json'))
    for task, w in meta['per_task_winners'].items():
        entry = thresholds['per_task'][task]
        entry['value'] = w['val']['rmse'] if entry['metric'] == 'rmse' else w['val']['pr_auc']
    for r in calib:
        task = r['calibration'][0]['task']
        platt = next(c for c in r['calibration'] if c['method'] == 'platt_sigmoid')
        thresholds['calibration_ece'][task]['value'] = platt['ece']
    json.dump(thresholds, open('ml/results/metric_thresholds.json', 'w'), indent=2)
    "

Usage:
    python ml/check_regression_gate.py

Exit code 0 if everything is within tolerance, 1 if anything regressed
(prints a human-readable report either way).

--- Rollback mode (--compare-to <git-ref>) --------------------------------

Per TODO/ml/TODO_model_registry.md's open item ("Механізм відкату (rollback)
до попередньої версії моделі в разі регресії метрик"): models/production/
models.joblib (the actual fitted model bundle, ~125MB) is gitignored, not
committed - only models/production/metadata.json (its metrics/model-name
record) is. That means there is no stored prior binary to instantly swap
back in if a newly registered model regresses. `git log -- models/
production/metadata.json` already gives a usable history of every prior
registration's per-task metrics for free (see the 3 commits currently in
this repo's history), so no separate metadata_history/ snapshot directory
is added here - it would just duplicate what git already tracks.

    python ml/check_regression_gate.py --compare-to <git-ref>

reads the CURRENT models/production/metadata.json from disk (freshly
regenerated by an earlier pipeline step, same as the default mode) and
`git show <git-ref>:models/production/metadata.json` for the historical
one, then diffs every task's val PR-AUC (classification) / val RMSE
(regression) between them using the same tolerances as the default gate
(ml/results/metric_thresholds.json). Exit code 1 if the CURRENT metadata
has regressed past the historical one for any task past tolerance.

Honest scope: this detects the regression and tells you which commit was
last known good - it does NOT swap models.joblib back in place, because
that binary was never stored for the historical commit either (it is
rebuilt fresh from ml/model_registry.py every run and gitignored). Actually
rolling back therefore means: `git checkout <git-ref>` (or `git revert`
back to it) and RE-RUN the training pipeline there (ml/preprocess.py,
ml/baseline.py, ml/experiments_per_task_models.py, ml/model_registry.py)
to regenerate a models.joblib that matches that commit's metadata.json -
not an instant binary swap. That is a deliberate, size-appropriate scope
decision for this project (same rationale as the documented decision to
skip MLflow/DVC): a real model-artifact store is out of scope here.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METADATA_PATH = ROOT / "models" / "production" / "metadata.json"
CALIBRATION_PATH = ROOT / "ml" / "results" / "calibration_metrics.json"
THRESHOLDS_PATH = ROOT / "ml" / "results" / "metric_thresholds.json"


def check_per_task_metrics(metadata: dict, thresholds: dict) -> list[dict]:
    tol_pr_auc = thresholds["tolerance"]["classification_pr_auc"]
    tol_rmse = thresholds["tolerance"]["regression_rmse"]
    winners = metadata.get("per_task_winners", {})

    results = []
    for task, floor in thresholds["per_task"].items():
        winner = winners.get(task)
        if winner is None:
            results.append({
                "task": task, "ok": False,
                "reason": "no registered production model for this task (was registered when thresholds were committed)",
            })
            continue

        current = winner["val"].get(floor["metric"])
        if current is None:
            results.append({"task": task, "ok": False, "reason": f"current val.{floor['metric']} is missing"})
            continue

        if floor["direction"] == "higher_is_better":
            gate = floor["value"] - tol_pr_auc
            ok = current >= gate
            reason = f"val {floor['metric']}={current:.4f} vs floor {floor['value']:.4f} (- tol {tol_pr_auc} = {gate:.4f})"
        else:
            gate = floor["value"] + tol_rmse
            ok = current <= gate
            reason = f"val {floor['metric']}={current:.4f} vs floor {floor['value']:.4f} (+ tol {tol_rmse} = {gate:.4f})"

        results.append({"task": task, "ok": ok, "reason": reason, "current": current, "floor": floor["value"]})
    return results


def check_calibration_ece(calibration_records: list[dict] | None, thresholds: dict) -> list[dict]:
    tol_ece = thresholds["tolerance"]["calibration_ece"]
    results = []

    by_task = {}
    if calibration_records:
        for r in calibration_records:
            task = r["calibration"][0]["task"]
            platt = next((c for c in r["calibration"] if c["method"] == "platt_sigmoid"), None)
            if platt is not None:
                by_task[task] = platt["ece"]

    for task, floor in thresholds["calibration_ece"].items():
        current = by_task.get(task)
        if current is None:
            results.append({
                "task": task, "ok": False,
                "reason": "no current platt_sigmoid ECE found (ml/calibration.py may not have run, or no longer covers this task)",
            })
            continue
        gate = floor["value"] + tol_ece
        ok = current <= gate
        results.append({
            "task": task, "ok": ok,
            "reason": f"val ECE={current:.4f} vs floor {floor['value']:.4f} (+ tol {tol_ece} = {gate:.4f})",
            "current": current, "floor": floor["value"],
        })
    return results


def _val_metric_and_direction(winner: dict) -> tuple[str, float | None, bool] | None:
    """Infers whether a per-task winner's `val` dict is a classification
    (pr_auc, higher is better) or regression (rmse, lower is better)
    record, and returns (metric_name, value, higher_is_better) - or None if
    neither key is present (e.g. an empty val dict)."""
    val = winner.get("val", {})
    if "pr_auc" in val:
        return "pr_auc", val["pr_auc"], True
    if "rmse" in val:
        return "rmse", val["rmse"], False
    return None


def load_metadata_at_ref(git_ref: str) -> dict:
    """git show <ref>:models/production/metadata.json - the historical
    metadata for a prior registration, without needing any separate
    snapshot directory (see module docstring's rollback-mode section)."""
    proc = subprocess.run(
        ["git", "show", f"{git_ref}:models/production/metadata.json"],
        capture_output=True, text=True, cwd=ROOT, check=False,
    )
    if proc.returncode != 0:
        raise SystemExit(
            f"ERROR: could not read models/production/metadata.json at git ref "
            f"'{git_ref}': {proc.stderr.strip()}"
        )
    return json.loads(proc.stdout)


def compare_to_historical_metadata(current: dict, historical: dict, thresholds: dict, git_ref: str) -> list[dict]:
    """For every task registered in the HISTORICAL metadata, compare its
    val metric against the CURRENT metadata's val metric for that same
    task, using the same tolerances as the default gate. A task present
    historically but missing/no-longer-registered now is reported as a
    regression (a real, worse-than-before state), not silently skipped."""
    tol_pr_auc = thresholds["tolerance"]["classification_pr_auc"]
    tol_rmse = thresholds["tolerance"]["regression_rmse"]

    current_winners = current.get("per_task_winners", {})
    historical_winners = historical.get("per_task_winners", {})

    results = []
    for task, hist_winner in historical_winners.items():
        hist_metric = _val_metric_and_direction(hist_winner)
        if hist_metric is None:
            continue
        metric_name, hist_value, higher_is_better = hist_metric

        current_winner = current_winners.get(task)
        if current_winner is None:
            results.append({
                "task": task, "ok": False,
                "reason": f"no longer registered in current metadata.json (was registered at {git_ref})",
            })
            continue

        current_metric = _val_metric_and_direction(current_winner)
        if current_metric is None or current_metric[0] != metric_name:
            results.append({
                "task": task, "ok": False,
                "reason": f"current val.{metric_name} is missing or metric type changed",
            })
            continue
        current_value = current_metric[1]
        if current_value is None or hist_value is None:
            results.append({"task": task, "ok": False, "reason": f"val.{metric_name} undefined on one side"})
            continue

        if higher_is_better:
            gate = hist_value - tol_pr_auc
            ok = current_value >= gate
            reason = (
                f"current val {metric_name}={current_value:.4f} vs {git_ref} "
                f"val {metric_name}={hist_value:.4f} (- tol {tol_pr_auc} = {gate:.4f})"
            )
        else:
            gate = hist_value + tol_rmse
            ok = current_value <= gate
            reason = (
                f"current val {metric_name}={current_value:.4f} vs {git_ref} "
                f"val {metric_name}={hist_value:.4f} (+ tol {tol_rmse} = {gate:.4f})"
            )
        results.append({
            "task": task, "ok": ok, "reason": reason,
            "current": current_value, "historical": hist_value,
        })
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--compare-to", metavar="GIT_REF", default=None,
        help="Rollback-detection mode: diff current models/production/metadata.json "
             "against `git show <GIT_REF>:models/production/metadata.json` instead of "
             "the committed metric_thresholds.json floor. See module docstring.",
    )
    args = parser.parse_args()

    if not METADATA_PATH.exists():
        print(f"ERROR: {METADATA_PATH} not found - run ml/model_registry.py first.")
        return 1
    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))

    if not THRESHOLDS_PATH.exists():
        print(f"ERROR: {THRESHOLDS_PATH} not found - nothing to check against.")
        return 1
    thresholds = json.loads(THRESHOLDS_PATH.read_text(encoding="utf-8"))

    if args.compare_to:
        historical_metadata = load_metadata_at_ref(args.compare_to)
        rollback_results = compare_to_historical_metadata(metadata, historical_metadata, thresholds, args.compare_to)

        print(f"=== Rollback check: current metadata.json vs. git ref '{args.compare_to}' ===")
        for r in rollback_results:
            status = "PASS" if r["ok"] else "FAIL"
            print(f"  [{status}] {r['task']}: {r['reason']}")

        failures = [r for r in rollback_results if not r["ok"]]
        print(f"\n{len(rollback_results) - len(failures)} / {len(rollback_results)} tasks unregressed vs. {args.compare_to}.")
        if failures:
            print(
                f"REGRESSION DETECTED vs. {args.compare_to}: {len(failures)} task(s) regressed.\n"
                f"To roll back: `git checkout {args.compare_to}` (or revert to it), then re-run "
                "the training pipeline there (ml/preprocess.py && ml/baseline.py && "
                "ml/experiments_per_task_models.py && ml/model_registry.py) to regenerate a "
                "models.joblib that matches that commit's metadata.json. The model binary "
                "itself is not stored/versioned (gitignored, ~125MB) - only metadata.json is - "
                "so this is a re-run, not an instant artifact swap. See this script's module "
                "docstring for the full rationale."
            )
            return 1
        print(f"No regression detected vs. {args.compare_to}.")
        return 0

    calibration_records = json.loads(CALIBRATION_PATH.read_text(encoding="utf-8")) if CALIBRATION_PATH.exists() else None
    if calibration_records is None:
        print(f"WARNING: {CALIBRATION_PATH} not found - skipping calibration ECE gate (run ml/calibration.py first).")

    metric_results = check_per_task_metrics(metadata, thresholds)
    ece_results = check_calibration_ece(calibration_records, thresholds)

    print("=== Per-task metric regression gate (val PR-AUC / val RMSE) ===")
    for r in metric_results:
        status = "PASS" if r["ok"] else "FAIL"
        print(f"  [{status}] {r['task']}: {r['reason']}")

    print("\n=== Calibration ECE regression gate (val, Platt/sigmoid) ===")
    for r in ece_results:
        status = "PASS" if r["ok"] else "FAIL"
        print(f"  [{status}] {r['task']}: {r['reason']}")

    failures = [r for r in metric_results + ece_results if not r["ok"]]
    print(f"\n{len(metric_results) + len(ece_results) - len(failures)} / {len(metric_results) + len(ece_results)} checks passed.")
    if failures:
        print(f"REGRESSION GATE FAILED: {len(failures)} check(s) regressed past their committed floor.")
        return 1
    print("Regression gate passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
